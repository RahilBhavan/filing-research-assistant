"""Regenerate evaluation/treasury/REPORT.md from committed run files (no model calls)."""
import json
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from filing_assistant import treasury_eval as t  # noqa: E402
from filing_assistant.providers import PRICES  # noqa: E402

EVAL = ROOT/'evaluation/treasury'
RUNS = [('heldout-haiku-cli', 'Claude Haiku 5.5 (via Claude Code CLI adapter)'),
        ('heldout-extractive', 'Extractive fallback (no model)'),
        ('heldout-ollama-qwen0.5b', 'qwen2.5:0.5b (local, Ollama)')]
LABELS = {'bm25': 'BM25 (existing)', 'lsa': 'LSA, 64-dim corpus-fitted (existing)', 'lsa-hybrid': 'LSA + BM25 RRF (existing)',
          'dense': 'bge-small-en-v1.5 embeddings (new)', 'dense-hybrid': 'bge-small + BM25 RRF (new, used for generation)'}


def frac(pair):
    return '—' if pair is None else '{}/{} ({:.0f}%)'.format(pair[0], pair[1], 100*pair[0]/pair[1]) if pair[1] else '0/0'


def api_cost(run):
    """Same token counts priced as an uncached direct API call."""
    inp, out = PRICES['claude-haiku-5-5']
    costs = []
    for line in (EVAL/'runs'/(run + '.jsonl')).read_text().splitlines():
        u = json.loads(line)['usage']
        if 'output_tokens' in u:
            tokens_in = u.get('input_tokens', 0) + u.get('cache_creation_input_tokens', 0) + u.get('cache_read_input_tokens', 0)
            costs.append((tokens_in*inp + u['output_tokens']*out)/1e6)
    return statistics.mean(costs)


def main():
    retrieval = json.loads((EVAL/'heldout-retrieval.json').read_text())
    dev = json.loads((EVAL/'dev-retrieval.json').read_text())
    scores = {run: t.score(run) for run, _ in RUNS}
    judges = {run: json.loads((EVAL/'runs'/(run + '-judge.json')).read_text()) for run, _ in RUNS}
    lines = ['# Treasury filings: retrieval and checked LLM answers', '',
             'Generated by `python work/build_treasury_report.py` from committed run files. Questions and gold labels are author-written by the Claude Code agent, not human-verified. 40 held-out questions (30 answerable, 10 unanswerable) over six filings; frozen before any generator run (`frozen.json`).', '',
             '## Retrieval (held-out, 30 answerable; a hit is any gold passage)', '',
             '| Method | Recall@1 | Recall@3 | Recall@5 | MRR@5 | Dev recall@5 (6) |', '|---|---|---|---|---|---|']
    for m, r in retrieval.items():
        lines.append('| {} | {} | {} | {} | {:.3f} | {}/6 |'.format(LABELS[m], frac([r['recall@1'], 30]), frac([r['recall@3'], 30]), frac([r['recall@5'], 30]), r['mrr'], dev[m]['recall@5']))
    lines += ['', 'The generation method (dense-hybrid, top 5) was chosen on the 6-question dev split before held-out runs (`selection.json`). On held-out, plain dense retrieval had higher recall@5 (28 vs 27); the choice was not revisited.', '',
              '## Generation (held-out, 40 questions, dense-hybrid top 5)', '',
              '| Writer | Correct, judge (of 30) | Correct, author (of 30) | Judge–author agreement | Unanswerable abstained | False abstentions | Raw citation faithfulness | Served quotes verbatim | p50 latency | Cost / question |', '|---|---|---|---|---|---|---|---|---|---|']
    for run, label in RUNS:
        s = scores[run]
        cost = '${:.5f} CLI-reported; ≈${:.5f} direct API'.format(s['mean_cost_usd'], api_cost(run)) if run == 'heldout-haiku-cli' else '$0 (local)'
        lines.append('| {} | {} | {} | {} | {} | {} | {} | {} | {} | {} |'.format(label, frac(s['judge_correct']), frac(s['author_correct']), frac(s['judge_author_agreement']), frac(s['unanswerable_abstained']), frac(s['false_abstentions']), frac(s['raw_citation_faithfulness']), frac(s['served_quotes_verbatim']), '{:.2f} s'.format(s['p50_latency_s']), cost))
    total_agree = [sum(scores[r]['judge_author_agreement'][i] for r, _ in RUNS) for i in (0, 1)]
    labels_all = json.loads((EVAL/'author-labels.json').read_text())
    negatives = [(r, k) for r, _ in RUNS for k, v in labels_all[r].items() if v == 'incorrect' and k in judges[r]]
    neg_agree = sum(judges[r][k]['verdict'] == 'incorrect' for r, k in negatives)
    lines += ['', 'Definitions:', '',
              '- **Raw citation faithfulness**: of the model outputs that tried to answer, the share whose every quote was verbatim in a retrieved, cited passage and whose every number appeared in a quote. Failures are rejected and served as abstentions.',
              '- **Served quotes verbatim** is 100% by construction: the checker runs before anything is shown.',
              '- **Correct**: abstaining on an answerable question counts as incorrect; serving an answer to an unanswerable one is scored separately. The judge (Claude Sonnet via the CLI, a different model from the writer) sees only served answers to answerable questions. Author labels were committed before the judge ran.',
              '- **Agreement across all three writers: {}/{}.** On the Haiku run every served answer was correct by both raters, so its 26/26 agreement says little about the judge; the informative cases are the extractive and qwen runs, which contain {} author-incorrect items (judge agreed on {}).'.format(*total_agree, len(negatives), neg_agree),
              '- **Latency** is the writer call only. Dense-hybrid retrieval adds about 14 ms (p50, CPU). The Haiku figure goes through the CLI, which adds process start-up; the CLI-reported API time p50 was about 2.0 s.',
              '- **Cost**: the CLI reports list price including a one-hour prompt-cache write premium it adds. "Direct API" prices the same token counts at $0.10 / $0.50 per million input/output tokens without caching. No API key was available on the build machine, so the Anthropic provider itself was exercised only by unit tests.', '',
              '## Every Haiku miss and abstention', '', '| ID | Question | Outcome | Cause |', '|---|---|---|---|']
    rows = {r['id']: r for r in t.load('heldout')}
    ret = {q['id']: q['first_gold_rank'] for q in retrieval['dense-hybrid']['per_question']}
    for line in (EVAL/'runs/heldout-haiku-cli.jsonl').read_text().splitlines():
        r = json.loads(line); q = rows[r['id']]
        if q['answerable'] and r['status'] != 'answered':
            cause = 'gold passage not in top 5 (dense-hybrid)' if ret[r['id']] is None else 'gold retrieved at rank {}'.format(ret[r['id']])
            if r['reason'] == 'rejected:number_not_in_quotes':
                cause += '; answer was right but restated the fiscal year end ("August 31, 2025"), which was not inside its quote, so the checker rejected it'
            lines.append('| {} | {} | {} | {} |'.format(r['id'], q['question'], r['reason'], cause))
    lines += ['', '## Other observed failures', '']
    notes = json.loads((EVAL/'author-labels.json').read_text())['_about']['observations']
    lines += ['- `{}`: {}'.format(k, v) for k, v in notes.items()]
    disagreements = [(run, k) for run, _ in RUNS for k, v in judges[run].items() if k in json.loads((EVAL/'author-labels.json').read_text())[run] and v['verdict'] != json.loads((EVAL/'author-labels.json').read_text())[run][k]]
    for run, k in disagreements:
        lines.append('- Judge/author disagreement `{}/{}`: judge said {} ("{}"); author said incorrect.'.format(run, k, judges[run][k]['verdict'], judges[run][k]['reason']))
    lines += ['', '## Limits', '',
              '- 40 questions is small: one question moves a rate by 2.5–3.3 points. No confidence intervals are claimed.',
              '- Questions, gold passages, reference answers and correctness labels were all written by the same agent that built the system. None were reviewed by a human.',
              '- Single run per writer. Haiku output is not sampled deterministically, so a rerun can differ.',
              '- The checker proves quotes are verbatim and numbers are quoted. It does not prove the answer is relevant (qwen t17), that the quotes support a claim written in words (qwen t01), or that non-numeric entities are quoted (Haiku t08).',
              '- Narrative sections only (Business, MD&A, Risk Factors); facts that appear only in tables or notes are out of scope and count as unanswerable here.', '']
    (EVAL/'REPORT.md').write_text('\n'.join(lines))
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
